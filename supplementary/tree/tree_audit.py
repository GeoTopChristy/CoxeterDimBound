"""Independent, local reconstruction of the tree-deletion certificates.

No source manuscript or previous data are changed. Arithmetic is rational.
Run with python -B tree_audit.py.
The input supports are generated by the complete finite/affine A/B/D
one-node support rules, not by copying the reported 79,113 records.
"""
from fractions import Fraction as F
from functools import lru_cache
from itertools import product
from collections import Counter, deque
from pathlib import Path
import json, time, platform

OUT=Path(__file__).absolute().parent
GRID=tuple(map(F,('1/3','2/5','1/2','3/5','2/3','3/4','4/5','1','5/4','3/2','2')))
TYPES=('AA','BA','DA','BB','BD','DD')
EXCEPT_ARMS={(1,2,2),(1,2,3),(1,2,4),(1,2,5),(1,3,3)}

def component_supports(trunk,kind,leaves,decor_side):
    """All nonempty PSD one-node extensions of one finite component.

    trunk is ordered left-to-right; decorated endpoint has extra B/D leaves.
    Empty support and joins of two different components are added elsewhere.
    """
    result=set()
    def add(*s): result.add(tuple(sorted(s)))
    if kind=='A':
        for i in (trunk[0],trunk[-1]):
            add((i,3)); add((i,4))
        for i in (trunk[1],trunk[-2]): add((i,3))
        add((trunk[0],3),(trunk[-1],3))
        k=len(trunk)
        for pos in range(2,k-2):
            if tuple(sorted((1,pos,k-1-pos))) in EXCEPT_ARMS:
                add((trunk[pos],3))
        joins=(trunk[0],trunk[-1])
    else:
        ordinary=trunk[-1] if decor_side=='left' else trunk[0]
        neighbor=trunk[-2] if decor_side=='left' else trunk[1]
        add((ordinary,3));add((ordinary,4));add((neighbor,3))
        if kind=='D' and len(trunk)+len(leaves) in (7,8):
            for i in leaves:add((i,3))
        joins=(ordinary,)
    return result,joins

def base(endtype,P,k,Q):
    m=P+k+Q; a=P;b=P+k
    edges=[(i,i+1,3) for i in range(m)]
    nextnode=m+1;leafsets=[];diag={i:F(2) for i in range(m+1)}
    for side,kind in zip((0,m),endtype):
        leaves=[]
        for _ in range({'A':0,'B':1,'D':2}[kind]):
            z=nextnode;nextnode+=1;leaves.append(z)
            edges.append((side,z,4 if kind=='B' else 3))
            diag[z]=F(4 if kind=='B' else 2)
        leafsets.append(leaves)
    return m,a,b,edges,diag,leafsets,nextnode

@lru_cache(None)
def inverse_cached(diagonals,edges):
    n=len(diagonals)
    A=[[F(diagonals[i] if i==j else 0) for j in range(n)] for i in range(n)]
    for i,j,x in edges:A[i][j]=A[j][i]=F(x)
    rows=[r+[F(i==j) for j in range(n)] for i,r in enumerate(A)]
    for j in range(n):
        piv=rows[j][j];assert piv>0
        rows[j]=[x/piv for x in rows[j]]
        for i in range(n):
            if i!=j and rows[i][j]:
                x=rows[i][j];rows[i]=[u-x*v for u,v in zip(rows[i],rows[j])]
    return tuple(tuple(row[n:]) for row in rows)

def unmarked_inverse(edges,diag,a,b):
    keep=set(diag)-{a,b};adj={i:[] for i in keep}
    for u,v,m in edges:
        if u in keep and v in keep:adj[u].append(v);adj[v].append(u)
    inv={}
    while keep:
        seed=min(keep);stack=[seed];component={seed}
        while stack:
            u=stack.pop()
            for v in adj[u]:
                if v not in component:component.add(v);stack.append(v)
        nodes=sorted(component);keep-=component;index={u:i for i,u in enumerate(nodes)}
        ee=tuple((index[u],index[v],-2 if m==4 else -1) for u,v,m in edges if u in component and v in component)
        mat=inverse_cached(tuple(diag[u] for u in nodes),ee)
        inv.update({(u,v):mat[i][j] for i,u in enumerate(nodes) for j,v in enumerate(nodes)})
    return inv

def all_supports(deleted,m,endtype,leaves):
    left,jleft=component_supports(list(range(deleted)),endtype[0],leaves[0],'left')
    right,jright=component_supports(list(range(deleted+1,m+1)),endtype[1],leaves[1],'right')
    result={()}|left|right
    for x,y in product(jleft,jright):result.add(tuple(sorted(((x,3),(y,3)))))
    return sorted(result)

def full_allowed(m,endtype,leaves):
    if endtype=='AA':return component_supports(list(range(m+1)),'A',[],'left')[0]
    if endtype in ('BA','DA'):return component_supports(list(range(m+1)),endtype[0],leaves[0],'left')[0]
    return set()

def variants(support,which,m,P,Q,endtype,allowed):
    """Return minimal opposite coupling and possible external E7/E8 leaf.

    A zero opposite coupling in an already-indefinite larger C+new diagram
    is a relaxation. An omitted external leaf is retained only in the two
    finite exceptions capable of supplying missing opposite indefiniteness.
    """
    opp=1 if not support or support in allowed else 0
    ans=[(opp,False)]
    exceptional=(which=='c' and endtype[0]=='A' and P in (5,6) and support==((1,3),)) or (which=='d' and endtype[1]=='A' and Q in (5,6) and support==((m-1,3),))
    if exceptional:
        assert opp==1
        ans.append((0,True))
    return ans

def schur(edges,diag,inv,a,b,cs,ds,cv,dv):
    ret=(a,b,'c','d'); direct=[[F(0) for _ in range(4)] for _ in range(4)]
    direct[0][0]=direct[1][1]=F(2)
    conn=[{} for _ in range(4)]
    for u,v,label in edges:
        mag=F(-2 if label==4 else -1)
        if u in (a,b):conn[0 if u==a else 1][v]=mag
        if v in (a,b):conn[0 if v==a else 1][u]=mag
    for index,support,(opp,external) in ((2,cs,cv),(3,ds,dv)):
        heavy=any(label==4 for _,label in support)
        direct[index][index]=F(4 if heavy else 2)-(F(1,2) if external else 0)
        for u,label in support:
            mag=F(-2 if heavy else -1)
            if u in (a,b):j=0 if u==a else 1;direct[index][j]=direct[j][index]=mag
            else:conn[index][u]=mag
        opposite=0 if index==2 else 1
        direct[index][opposite]=direct[opposite][index]=F(-opp)
    R=[[direct[i][j]-sum(x*inv.get((u,v),F(0))*y for u,x in conn[i].items() for v,y in conn[j].items()) for j in range(4)] for i in range(4)]
    return R

def psd2(A,B,C):return A>=0 and C>=0 and A*C-B*B>=0

def failed(R):
    for i in (2,3):
        if R[i][i]<=0:return {'condition':'S+mark PD','mark':i,'pivot':str(R[i][i])}
    for i,j in ((1,2),(0,3),(2,3)):
        if not psd2(R[i][i],R[i][j],R[j][j]):
            return {'condition':'adjacent angle PSD','pair':[i,j],'matrix':[[str(R[i][i]),str(R[i][j])],[str(R[i][j]),str(R[j][j])]]}
    return None

def short_path(edges,cs,ds,cv,dv,a,b,m,P,k,Q):
    """BFS after deleting the two other marks and every growable segment.

    This directly supplies a path unaffected by all future path lengths.
    The omitted external leaf has no role in paths between distinct marks.
    """
    grow=set()
    if P==9:grow.update((i,i+1) for i in range(2,a-2))
    if k==10:grow.update((i,i+1) for i in range(a+2,b-2))
    if Q==9:grow.update((i,i+1) for i in range(b+2,m-2))
    E=[(u,v) for u,v,_ in edges if (u,v) not in grow]
    E += [('c',u) for u,_ in cs]+[('d',u) for u,_ in ds]
    if cv[0]:E.append(('c',a))
    if dv[0]:E.append(('d',b))
    marks={a,b,'c','d'}
    for source,target in ((b,'c'),('c','d'),('d',a)):
        forbidden=marks-{source,target};adj={}
        for u,v in E:
            if u not in forbidden and v not in forbidden:adj.setdefault(u,[]).append(v);adj.setdefault(v,[]).append(u)
        queue=deque([source]);parents={source:None};dist={source:0}
        while queue:
            u=queue.popleft()
            if dist[u]>=7:continue
            for v in adj.get(u,()):
                if v not in parents:parents[v]=u;dist[v]=dist[u]+1;queue.append(v)
        if target in parents:
            path=[target]
            while path[-1]!=source:path.append(parents[path[-1]])
            path.reverse()
            return {'pair':[source,target],'path':path,'distance':len(path)-1,'avoids_all_variable_segments':True}
    return None

def negative_witness(R):
    for x in GRID:
        p=R[0][0]+2*x*R[0][2]+x*x*R[2][2]
        if p>=0:continue
        for y in GRID:
            q=R[1][1]+2*y*R[1][3]+y*y*R[3][3]
            if q>=0:continue
            r=R[0][1]+y*R[0][3]+x*R[2][1]+x*y*R[2][3]
            det=p*q-r*r
            if det>0:return {'x':str(x),'y':str(y),'matrix':[[str(p),str(r)],[str(r),str(q)]],'determinant':str(det)}
    return None

def run():
    started=time.time();totals=Counter();bytype={};unresolved=[];minimum=None
    output=(OUT/'records.jsonl').open('w',encoding='utf-8')
    for endtype in TYPES:
        counts=Counter()
        for P,k,Q in product(range(5,10),(8,9,10),range(5,10)):
            m,a,b,edges,diag,leaves,nextnode=base(endtype,P,k,Q)
            inv=unmarked_inverse(edges,diag,a,b)
            supports_c=all_supports(a,m,endtype,leaves);supports_d=all_supports(b,m,endtype,leaves)
            allowed=full_allowed(m,endtype,leaves)
            for cs,ds in product(supports_c,supports_d):
                for cv,dv in product(variants(cs,'c',m,P,Q,endtype,allowed),variants(ds,'d',m,P,Q,endtype,allowed)):
                    row={'endtype':endtype,'P':P,'ell':k,'Q':Q,'support_c':cs,'support_d':ds,'variant_c':cv,'variant_d':dv}
                    R=schur(edges,diag,inv,a,b,cs,ds,cv,dv)
                    cert=failed(R)
                    if cert:outcome='failed'
                    else:
                        cert=short_path(edges,cs,ds,cv,dv,a,b,m,P,k,Q)
                        if cert:outcome='short'
                        else:
                            cert=negative_witness(R)
                            outcome='negative' if cert else 'unresolved'
                            if cert:
                                determinant=F(cert['determinant'])
                                minimum=determinant if minimum is None else min(minimum,determinant)
                    counts[outcome]+=1;totals[outcome]+=1
                    row.update(outcome=outcome,certificate=cert)
                    if outcome=='unresolved':row['R']=[[str(v) for v in rr] for rr in R];unresolved.append(row)
                    output.write(json.dumps(row,separators=(',',':'))+'\n')
        bytype[endtype]=dict(counts)
        print(json.dumps({'endtype':endtype,'counts':dict(counts),'seconds':round(time.time()-started,2)}),flush=True)
    output.close()
    summary={'scope':'Fresh exact reconstruction of the complete stated tree support families; input rules in tree_audit.py',
      'initial_chains':450,'counts':dict(totals),'bytype':bytype,'minimum_negative_witness_determinant':str(minimum),
      'unresolved_count':len(unresolved),'all_records_certified':not unresolved,'seconds':round(time.time()-started,2),
      'runtime':{'python':platform.python_version(),'platform':platform.platform(),'dependencies':'Python standard library only'},
      'variable_segments':'For P=9, ell=10, Q=9 retain nodes within two steps of marks and original endpoints; every short certificate avoids all three interior segments.'}
    (OUT/'summary.json').write_text(json.dumps(summary,indent=2)+'\n',encoding='utf-8')
    (OUT/'unresolved.json').write_text(json.dumps(unresolved,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(summary,indent=2),flush=True)

if __name__=='__main__':run()
